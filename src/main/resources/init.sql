CREATE TABLE IF NOT EXISTS unit (
    id INTEGER PRIMARY KEY,
    unit_key VARCHAR(40) NOT NULL UNIQUE,
    category VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS unit_translation (
    unit_id INTEGER NOT NULL REFERENCES unit(id),
    lang CHAR(2) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(200) NOT NULL,
    PRIMARY KEY (unit_id, lang)
);

CREATE TABLE IF NOT EXISTS speed_measurement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    value DOUBLE PRECISION NOT NULL,
    unit_id INTEGER NOT NULL REFERENCES unit(id)
);

CREATE TABLE IF NOT EXISTS calculation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    input_value DOUBLE PRECISION NOT NULL,
    from_unit_id INTEGER NOT NULL REFERENCES unit(id),
    to_unit_id INTEGER NOT NULL REFERENCES unit(id),
    result DOUBLE PRECISION NOT NULL,
    lang CHAR(2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS time_measurement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calculation_id BIGINT NOT NULL REFERENCES calculation(id),
    elapsed_millis BIGINT NOT NULL
);

